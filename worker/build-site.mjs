// Bundle the public site files into site-files.js so worker.js can serve them.
// Text files as text; the one image (og.png, the link preview) as base64.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, extname, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const entries = ['index.html', 'admin.html', 'privacy.html', 'og.png', 'config.js', 'sw.js', 'manifest.webmanifest', 'icon.svg', 'css', 'js'];
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml', '.webmanifest': 'application/manifest+json', '.png': 'image/png'
};
const BINARY = new Set(['.png']);
const files = {};
function add(p) {
  const full = join(root, p);
  if (statSync(full).isDirectory()) { for (const f of readdirSync(full)) add(join(p, f)); return; }
  const type = TYPES[extname(p)];
  if (!type) throw new Error('unsupported file type: ' + p);
  files['/' + relative(root, full)] = BINARY.has(extname(p))
    ? { type, b64: true, body: readFileSync(full).toString('base64') }
    : { type, body: readFileSync(full, 'utf8') };
}
entries.forEach(add);
writeFileSync(new URL('site-files.js', import.meta.url), '// generated by build-site.mjs, do not edit\nexport default ' + JSON.stringify(files) + ';\n');
console.log('bundled', Object.keys(files).length, 'site files');
